import { expect, test, type Page } from '@playwright/test'

async function step(page: Page, name: string) {
  await page.getByRole('navigation', { name: 'Шаги оценки' }).getByRole('link', { name, exact: false }).click()
}

test('landing → guest copy → real calculation → 2D/3D replay → report → save account', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const session = page.waitForResponse((r) => r.url().endsWith('/auth/guest') && r.request().method() === 'POST')
  await page.goto('/')
  await page
    .getByRole('link', { name: /Попробовать без регистрации/ })
    .first()
    .click()
  expect((await session).status()).toBe(200)
  await page.getByRole('link', { name: 'Начать со склада', exact: true }).click()
  await expect(page).toHaveURL(/\/projects\/[\w-]+\/object$/)
  const projectPath = new URL(page.url()).pathname.replace('/object', '')
  await expect(page.getByRole('complementary', { name: 'Режим проекта' })).toBeVisible()
  await page.reload()
  await expect(page).toHaveURL(new RegExp(`${projectPath}/object$`))
  await expect(page.getByRole('button', { name: 'Загрузить файл', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Шаги оценки' }).getByRole('link')).toHaveCount(5)
  await step(page, 'Роботы')
  await expect(page.getByRole('heading', { name: 'Роботы для вашего объекта' })).toBeVisible()
  await expect(page.locator('canvas').first()).toBeVisible()
  await step(page, 'Экономика')
  await expect(page.getByRole('link', { name: 'Робот как услуга', exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Все инструменты', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Шаги оценки' }).getByRole('link')).toHaveCount(9)
  await step(page, 'Риски')
  await expect(page.getByRole('heading', { name: 'Разброс результата' })).toBeVisible()
  await page.getByRole('button', { name: 'Короткий маршрут', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`${projectPath}/object$`))
  await step(page, 'Имитация')
  await expect(page.getByRole('button', { name: '2D-схема', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '2D-схема', exact: true }).click()
  await expect(page.getByRole('img', { name: /^Планировка/ })).toBeVisible()
  await expect(page.getByRole('slider', { name: 'Время имитации' })).toBeVisible()
  await page.getByRole('button', { name: '3D', exact: true }).click()
  await expect(page.locator('canvas').first()).toBeVisible()
  await expect(page.getByText('Считаем день имитацией', { exact: false })).not.toBeVisible({ timeout: 120_000 })
  await page.screenshot({ path: test.info().outputPath('guest-simulation.png') })
  await step(page, 'Решение')
  const downloaded = page.waitForEvent('download', { timeout: 120_000 })
  await page.getByRole('button', { name: 'Скачать PDF', exact: true }).click()
  const file = await downloaded
  expect(file.suggestedFilename()).toMatch(/\.pdf$/)
  expect(await file.failure()).toBeNull()
  await page.getByRole('link', { name: 'Сохранить в аккаунт', exact: true }).first().click()
  await expect(page.getByText(/Ваши временные проекты и результаты перейдут/)).toBeVisible()
  await page.getByLabel('Имя', { exact: true }).fill('Гостевой эксперт')
  await page.getByLabel('Эл. почта', { exact: true }).fill(`guest-${Date.now()}@example.org`)
  await page.getByLabel('Пароль (не короче 8 символов)', { exact: true }).fill('GuestDemo12345!')
  await page.getByRole('button', { name: 'Зарегистрироваться', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`${projectPath}/report$`))
  await expect(page.getByText('Ваш сохранённый пример', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('own blank project → CSV preview → apply → manual edit → reset', async ({ page }) => {
  await page.goto('/demo?new=1')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Название', { exact: true }).fill('Собственный склад из CSV')
  await expect(page.getByRole('radio', { name: 'Пустой проект', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Создать проект', exact: true }).click()
  await expect(page).toHaveURL(/\/projects\/[\w-]+$/)
  await step(page, 'Объект')
  await page.getByRole('button', { name: 'Загрузить файл', exact: true }).click()
  await page.locator('input[type="file"]').setInputFiles({
    name: 'my-warehouse.csv',
    mimeType: 'text/csv',
    buffer: Buffer.from('key;value\narea_m2;25000\nshift_hours;8\n'),
  })
  await expect(page.getByRole('heading', { name: 'Проверка параметров' })).toBeVisible()
  await page.getByRole('button', { name: /Применить/ }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText(/Импорт применён/)).toBeVisible()
  const saved = page.waitForResponse((r) => r.url().endsWith('/params/area_m2') && r.request().method() === 'PATCH')
  const area = page.locator('#param-area_m2 input')
  await area.fill('26000')
  await area.press('Tab')
  expect((await saved).status()).toBe(200)
  await expect(area).toHaveValue('26000')
  await page.getByRole('button', { name: 'Сбросить', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Сбросить демо', exact: true }).click()
  await expect(page).toHaveURL(/\/demo$/)
  await expect(page.getByRole('heading', { name: 'Демо без регистрации' })).toBeVisible()
  await page
    .getByRole('navigation', { name: 'Разделы', exact: true })
    .getByRole('link', { name: 'Проекты', exact: true })
    .click()
  await expect(page).toHaveURL(/\/demo$/)
  await expect(page.getByRole('heading', { name: 'Демо без регистрации' })).toBeVisible()
})
